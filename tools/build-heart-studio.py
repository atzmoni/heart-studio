# Builds heart-studio.html: the whole heart mapping studio (index.html and its modules, theme included) in one file
# that runs by double-click from the computer, with no server and no internet (fonts fall back to the system's).
# Run from the repository root:  python3 tools/build-heart-studio.py
import re

MODS = [("geo", "heart-geo.js"), ("gl", "heart-gl.js"), ("audio", "heart-audio.js"), ("engine", "heart-engine.js")]
VAR = {f: "M_" + n for n, f in MODS}

def imports_to_consts(code):
    def rep(m):
        what, f = m.group(1).strip(), m.group(2)
        if what.startswith("* as "): return f"const {what[5:].strip()} = {VAR[f]};"
        names = [x.strip().replace(" as ", ": ") for x in what.strip("{} ").split(",") if x.strip()]
        return f"const {{ {', '.join(names)} }} = {VAR[f]};"
    return re.sub(r'import\s+(\* as \w+|\{[^}]*\})\s+from\s+"\./(heart-[a-z]+\.js)(?:\?v=\d+)?";', rep, code)

parts = []
for n, f in MODS:
    code = imports_to_consts(open(f, encoding="utf-8").read())
    names = re.findall(r'^export\s+(?:async\s+)?(?:const|let|function|class)\s+(\w+)', code, re.M)
    code = re.sub(r'^export\s+', '', code, flags=re.M)
    parts.append(f"// ===== {f} =====\nconst M_{n} = (() => {{\n{code}\nreturn {{ {', '.join(names)} }};\n}})();\n")

html = open("index.html", encoding="utf-8").read()
a = html.index('<script type="module">') + len('<script type="module">')
b = html.index("</script>", a)
html = html[:a] + "\n" + "\n".join(parts) + "// ===== page =====\n" + imports_to_consts(html[a:b]) + html[b:]
html = html.replace('<link rel="stylesheet" href="theme.css?v=1">', "<style>\n" + open("theme.css", encoding="utf-8").read() + "</style>")
html = html.replace('<script src="theme.js?v=1"></script>', "<script>\n" + open("theme.js", encoding="utf-8").read() + "</script>")
html = html.replace('      <a href="./">→ לאפליקציה</a>\n', "")
html = html.replace("<title>Heart Mapping Studio</title>", "<title>Heart Mapping Studio</title>\n<!-- Generated by tools/build-heart-studio.py from index.html: edit those files, not this one. -->")
assert re.search(r"^\s*import\s", html, re.M) is None and "?v=1" not in html
open("heart-studio.html", "w", encoding="utf-8").write(html)
print("heart-studio.html", len(html), "bytes")
